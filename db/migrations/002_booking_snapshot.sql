-- ═══════════════════════════════════════════════════════════════════════════
--  002 — снимок расчёта в брони
--
--  Зачем: администратору нужно видеть, ИЗ ЧЕГО сложилась сумма, а не только
--  итог. Раньше строки расчёта и названия доп. услуг жили только в памяти
--  процесса и терялись при чтении брони из базы — админка показывала пустой
--  блок «из чего состоит цена».
--
--  Почему снимок, а не пересчёт на чтении: прайс может измениться. Пересчёт
--  задним числом показал бы строки, которые не сходятся с сохранённым итогом,
--  то есть соврал бы в отчёте. Снимок фиксирует то, что человек реально видел.
--
--  Миграция аддитивная и безопасная: ADD COLUMN IF NOT EXISTS с NOT NULL
--  и значением по умолчанию не переписывает существующие строки.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE bookings
  ADD COLUMN IF NOT EXISTS extra_names TEXT[] NOT NULL DEFAULT '{}';

ALTER TABLE bookings
  ADD COLUMN IF NOT EXISTS price_breakdown JSONB NOT NULL DEFAULT '[]'::jsonb;

-- Поиск брони по номеру платежа провайдера: используется вебхуком,
-- чтобы не обрабатывать один и тот же платёж дважды.
CREATE INDEX IF NOT EXISTS bookings_payment_reference_idx
  ON bookings ((payment ->> 'reference'))
  WHERE payment ->> 'reference' IS NOT NULL;

-- Результат выгрузки во внешнюю систему учёта. Нужен, чтобы администратор
-- видел неудачную синхронизацию в панели, а не узнавал о ней от клиента.
ALTER TABLE bookings
  ADD COLUMN IF NOT EXISTS crm_sync JSONB NOT NULL DEFAULT '{}'::jsonb;

-- Метки отправленных напоминаний («24h», «2h»). Без них повторный запуск
-- планировщика отправил бы клиенту то же напоминание второй раз.
ALTER TABLE bookings
  ADD COLUMN IF NOT EXISTS reminders_sent TEXT[] NOT NULL DEFAULT '{}';
