/**
 * ПРОВЕРКА КОНФИГУРАЦИИ ПРИ СТАРТЕ СЕРВЕРА
 *
 * Next вызывает `register()` один раз при подъёме процесса — это единственная
 * точка, где можно проверить окружение до того, как придут первые запросы.
 *
 * Зачем проверять здесь, а не «где-нибудь в health»: владелец или дежурный
 * должны увидеть проблему в логах деплоя сразу, а не узнать о ней от клиента,
 * который не смог забронировать.
 *
 * Сознательное решение — не ронять процесс. Отсутствие, скажем,
 * `NEXT_PUBLIC_SITE_URL` портит ссылки в разметке, но сайт при этом продолжает
 * принимать людей и звонки. Полностью лежащий сайт для бизнеса хуже, чем сайт
 * с честно отключённым бронированием и работающим телефоном. Поэтому критичные
 * расхождения печатаются громко в лог, попадают в /api/health и в
 * `npm run verify:production`, где уже возвращают ненулевой код выхода.
 */

export async function register(): Promise<void> {
  // Переменные окружения есть только в серверной среде Node
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  try {
    const { inspectEnv, formatEnvReport } = await import("./lib/config/env");
    const report = inspectEnv();

    if (!report.ok) {
      console.error(
        `\n══ КОНФИГУРАЦИЯ ПРОДАКШЕНА: ЕСТЬ ПРОБЛЕМЫ (${report.environment}) ══\n` +
          `${formatEnvReport(report)}\n` +
          `Подробности и порядок настройки: PRODUCTION.md\n`,
      );
    } else if (report.warnings.length > 0) {
      console.warn(`\n[конфигурация] ${report.environment}\n${formatEnvReport(report)}\n`);
    }
  } catch (error) {
    // Проверка конфигурации не должна мешать приложению подняться
    console.error("[конфигурация] не удалось выполнить проверку окружения:", error);
  }
}
